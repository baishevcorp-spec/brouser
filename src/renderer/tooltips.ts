/** Разрешить содержимое подсказки для элемента (data-tip-title > data-tip-id > data-tip). */
export function resolveTooltip(el: Element): TooltipContent | null {
  const dt = el as HTMLElement;
  // Динамическая rich-подсказка (сводка профиля, счётчик).
  if (dt.dataset.tipTitle !== undefined) {
    const title = dt.dataset.tipTitle;
    if (title) return { title, body: dt.dataset.tipBody || undefined };
  }
  // Статическая rich-подсказка из реестра.
  const id = dt.dataset.tipId;
  if (id && TOOLTIPS[id]) return TOOLTIPS[id];
  // Плоская строка (динамические состояния) — показывается как заголовок.
  const plain = dt.dataset.tip;
  if (plain) return { title: plain };
  return null;
}
